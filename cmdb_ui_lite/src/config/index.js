// ── 会话心跳 / 续期 ────────────────────────────────────────────────────────
// 心跳定时器周期（毫秒）：每该时长触发一次会话心跳。
//   - 用户活跃时：调 /renew 重签 token（sliding session，有效期滚动到当前时刻）
//   - 用户闲置时：调 /me 仅做超时检测
// 正常档位 60s；此前 10s 为临时测试值（配合后端 CMDB_TOKEN_MAX_AGE=30 快速验证超时链路）。
export const AUTH_RECHECK_MS = 60 * 1000

// 续期间隔（毫秒）：语义上「每个心跳周期最多续期一次」，与 AUTH_RECHECK_MS 对齐以避免高频打点。
// 当前心跳直接复用 AUTH_RECHECK_MS，此常量用于显式表达续期节奏，便于将来独立调参。
export const RENEW_INTERVAL_MS = AUTH_RECHECK_MS

// 活跃窗口（毫秒）：距上次用户交互不超过该时长即视为「活跃」并触发续期；
// 超过则停止续期，会话照常到期（由心跳 /me 检出后跳登录）。默认 2 分钟。
export const ACTIVITY_WINDOW_MS = 2 * 60 * 1000

export default {
  AUTH_RECHECK_MS,
  RENEW_INTERVAL_MS,
  ACTIVITY_WINDOW_MS,
}
